import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, '..');
const TODAY = process.env.CODE_QUALITY_TODAY ?? new Date().toISOString().slice(0, 10);

const SOURCE_EXTENSIONS = new Set(['.ts', '.tsx', '.js', '.jsx', '.mjs', '.py']);
const FRONTEND_TYPE_ESCAPE_RE =
  /\bas any\b|:\s*any\b|Record<string,\s*any>|@ts-ignore|@ts-expect-error/g;
const GENERATED_RE = /generated by|auto-generated|do not edit by hand|<auto-generated/i;

const DEFAULT_FILE_BUDGETS = {
  tsx: { advisory: 1_000, blocking: 1_500, label: 'React component file' },
  ts: { advisory: 1_500, blocking: 2_000, label: 'TypeScript module' },
  js: { advisory: 1_500, blocking: 2_000, label: 'JavaScript module' },
  mjs: { advisory: 1_500, blocking: 2_000, label: 'JavaScript module' },
  py: { advisory: 1_000, blocking: 1_500, label: 'Python module' },
};
const BUDGET_CONFIG_PATH = 'spec/code-quality-budgets.json';
const SECURITY_WAIVERS_PATH = 'spec/security-waivers.json';
const UI_QUALITY_BUDGETS_PATH = 'spec/ui-quality-budgets.json';

const GRADE_FLOORS = {
  C: 6.0,
  'C+': 6.5,
  'B-': 7.0,
  B: 7.5,
  'A-': 8.5,
  A: 9.0,
  'A+': 9.5,
};

function parseArgs(argv) {
  const args = {
    format: 'markdown',
    outJson: null,
    outMd: null,
    failBelow: null,
  };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--') continue;
    if (arg === '--json') args.format = 'json';
    else if (arg === '--markdown') args.format = 'markdown';
    else if (arg === '--out-json') args.outJson = argv[++i];
    else if (arg === '--out-md') args.outMd = argv[++i];
    else if (arg === '--fail-below') args.failBelow = argv[++i];
    else if (arg === '--help' || arg === '-h') {
      printHelp();
      process.exit(0);
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return args;
}

function printHelp() {
  console.log(`Usage: node scripts/code-quality-report.mjs [--json|--markdown] [--out-json PATH] [--out-md PATH] [--fail-below B-]

Produces a deterministic code-quality scorecard from tracked repository state.
The report scans source size budgets, type escape hotspots, tracked local
artifacts, quality waivers, configured gates, backend coverage configuration,
and open code-quality tracker rows.`);
}

function runGit(args) {
  const result = spawnSync('git', args, { cwd: REPO_ROOT, encoding: 'utf8' });
  if (result.status !== 0) {
    throw new Error(`git ${args.join(' ')} failed: ${result.stderr || result.stdout}`);
  }
  return result.stdout;
}

function trackedFiles() {
  return runGit(['ls-files'])
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean);
}

function readText(path) {
  return readFileSync(join(REPO_ROOT, path), 'utf8');
}

function countLines(text) {
  if (text.length === 0) return 0;
  return text.split('\n').length;
}

function isTestPath(path) {
  return (
    /\.test\.[tj]sx?$/.test(path) ||
    /\.spec\.[tj]sx?$/.test(path) ||
    path.includes('/tests/') ||
    path.includes('/__tests__/') ||
    path.endsWith('_test.py') ||
    path.includes('/test_')
  );
}

function isSourcePath(path) {
  const ext = extname(path);
  if (!SOURCE_EXTENSIONS.has(ext)) return false;
  if (path.includes('/node_modules/') || path.includes('/dist/') || path.includes('/.turbo/')) {
    return false;
  }
  if (path.startsWith('app/.venv/')) return false;
  return (
    path.startsWith('packages/') || path.startsWith('app/bim_ai/') || path.startsWith('scripts/')
  );
}

function sourceClass(path) {
  const ext = extname(path).replace('.', '');
  if (ext === 'tsx') return 'tsx';
  if (ext === 'ts') return 'ts';
  if (ext === 'py') return 'py';
  if (ext === 'mjs' || ext === 'js' || ext === 'jsx') return ext === 'mjs' ? 'mjs' : 'js';
  return 'other';
}

function hasGeneratedMarker(text, path) {
  if (path.includes('/generated/') || path.endsWith('.generated.ts')) return true;
  return GENERATED_RE.test(text.slice(0, 2_000));
}

function loadSourceInventory(files, fileSizeBudgets) {
  const rows = [];
  for (const path of files) {
    if (!isSourcePath(path)) continue;
    let text;
    try {
      text = readText(path);
    } catch {
      continue;
    }
    const lines = countLines(text);
    const kind = sourceClass(path);
    const budget = fileSizeBudgets[kind] ?? null;
    const generated = hasGeneratedMarker(text, path);
    rows.push({
      path,
      kind,
      lines,
      generated,
      budget,
      overAdvisory: Boolean(budget && !generated && lines > budget.advisory),
      overBlocking: Boolean(budget && !generated && lines > budget.blocking),
    });
  }
  rows.sort((a, b) => b.lines - a.lines || a.path.localeCompare(b.path));
  return rows;
}

function globToRegExp(glob) {
  let out = '^';
  for (let i = 0; i < glob.length; i += 1) {
    const ch = glob[i];
    const next = glob[i + 1];
    if (ch === '*' && next === '*') {
      out += '.*';
      i += 1;
    } else if (ch === '*') {
      out += '[^/]*';
    } else if ('\\^$+?.()|{}[]'.includes(ch)) {
      out += `\\${ch}`;
    } else {
      out += ch;
    }
  }
  out += '$';
  return new RegExp(out);
}

function loadWaivers() {
  const path = 'spec/quality-waivers.json';
  if (!existsSync(join(REPO_ROOT, path))) {
    return { path, waivers: [], active: [], expired: [], soon: [], missing: true };
  }
  const parsed = JSON.parse(readText(path));
  const today = new Date(`${TODAY}T00:00:00Z`);
  const waivers = Array.isArray(parsed.waivers) ? parsed.waivers : [];
  const active = [];
  const expired = [];
  const soon = [];
  for (const waiver of waivers) {
    const expires = new Date(`${waiver.expires}T00:00:00Z`);
    const daysUntilExpiry = Math.floor((expires - today) / 86_400_000);
    const row = { ...waiver, daysUntilExpiry };
    if (daysUntilExpiry < 0) expired.push(row);
    else {
      active.push(row);
      if (daysUntilExpiry <= 14) soon.push(row);
    }
  }
  return { path, waivers, active, expired, soon, missing: false };
}

