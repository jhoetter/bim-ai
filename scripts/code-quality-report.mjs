function waiverMatchesPath(waiver, path) {
  return (waiver.paths ?? []).some((pattern) => {
    if (pattern === path) return true;
    return globToRegExp(pattern).test(path);
  });
}

function ownershipForPath(config, path) {
  const match = config.ownership.find((row) => {
    if (typeof row?.pattern !== 'string') return false;
    return globToRegExp(row.pattern).test(path);
  });
  return match
    ? { owner: match.owner ?? 'unowned', trackerId: match.trackerId ?? null }
    : { owner: 'unowned', trackerId: null };
}

function budgetRows(sourceRows, waivers, budgetConfig) {
  return sourceRows
    .filter((row) => row.overAdvisory || row.overBlocking)
    .map((row) => {
      const matchingWaivers = waivers.filter((waiver) => waiverMatchesPath(waiver, row.path));
      const ownership = ownershipForPath(budgetConfig, row.path);
      const trackerIds = [
        ...new Set(
          [
            ownership.trackerId,
            ...matchingWaivers.map((waiver) => waiver.trackerId).filter(Boolean),
          ].filter(Boolean),
        ),
      ].sort();
      return {
        path: row.path,
        lines: row.lines,
        kind: row.kind,
        budget: row.budget,
        ...ownership,
        severity: row.overBlocking ? 'blocking' : 'advisory',
        waiverIds: matchingWaivers.map((waiver) => waiver.id).sort(),
        trackerIds,
        hasDisposition: matchingWaivers.length > 0 || trackerIds.length > 0,
      };
    });
}

function typeEscapeHotspots(files) {
  const rows = [];
  for (const path of files) {
    if (!path.startsWith('packages/web/src/')) continue;
    if (!/\.[tj]sx?$/.test(path)) continue;
    if (isTestPath(path)) continue;
    const text = readText(path);
    const matches = text.match(FRONTEND_TYPE_ESCAPE_RE) ?? [];
    if (matches.length === 0) continue;
    rows.push({ path, count: matches.length });
  }
  rows.sort((a, b) => b.count - a.count || a.path.localeCompare(b.path));
  return rows;
}

function trackedArtifactRows(files, budgetConfig) {
  const configuredPatterns =
    budgetConfig.generatedArtifactPolicy?.trackedLocalArtifactPatterns ?? [];
  const patterns =
    configuredPatterns.length > 0
      ? configuredPatterns.map((pattern) => ({
          code: pattern.includes('DS_Store')
            ? 'ds_store_tracked'
            : pattern.includes('coverage')
              ? 'coverage_tracked'
              : pattern.includes('tmp')
                ? 'tmp_tracked'
                : 'local_artifact_tracked',
          regex: new RegExp(pattern),
        }))
      : [
          { code: 'tmp_tracked', regex: /^tmp\// },
          { code: 'package_tmp_tracked', regex: /^packages\/[^/]+\/tmp\// },
          { code: 'coverage_tracked', regex: /(^|\/)\.coverage$/ },
          { code: 'ds_store_tracked', regex: /(^|\/)\.DS_Store$/ },
          { code: 'venv_tracked', regex: /(^|\/)\.venv\// },
          { code: 'pycache_tracked', regex: /(^|\/)__pycache__\// },
        ];
  return files
    .map((path) => {
      const match = patterns.find((pattern) => pattern.regex.test(path));
      return match ? { path, code: match.code } : null;
    })
    .filter(Boolean)
    .sort((a, b) => a.code.localeCompare(b.code) || a.path.localeCompare(b.path));
}

