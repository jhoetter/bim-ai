function trackerRows() {
  const tracker = readText('spec/code-quality-tracker.md');
  const rowRe =
    /^\| (CQ-\d{4}-\d{2}) \| (P\d)\s+\| (Open|Partial|Done|Blocked)\s+\| ([^|]+?)\s+\| ([^|]+?)\s+\|$/gm;
  const rows = [];
  let match;
  while ((match = rowRe.exec(tracker))) {
    rows.push({
      id: match[1],
      priority: match[2],
      status: match[3],
      theme: match[4].trim(),
      exitSignal: match[5].trim(),
    });
  }
  return rows;
}

function computeGrade({
  tracker,
  waivers,
  securityWaivers,
  budgetRows: budgets,
  artifacts,
  typeEscapes,
  scripts,
  securityGates,
  frontendTestEnvironments,
  contractParity,
  uiQualityBudgets,
  realPathCoverage,
}) {
  const p0Open = tracker.filter((row) => row.priority === 'P0' && row.status !== 'Done');
  const p1Open = tracker.filter((row) => row.priority === 'P1' && row.status !== 'Done');
  const expiredBlockingWaivers = waivers.expired.filter(
    (waiver) => waiver.severity === 'P0' || waiver.severity === 'P1',
  );
  const blockingBudgetsWithoutDisposition = budgets.filter(
    (row) => row.severity === 'blocking' && !row.hasDisposition,
  );
  const hasQualityReportScript = Boolean(scripts.root['quality:report']);
  const hasStrictGate = Boolean(scripts.root['verify:strict']);
  const hasSecurityHygiene = Boolean(securityGates.hygieneScript);
  const hasMaintainabilityBudgetGate = Boolean(scripts.root['maintainability:budgets']);

  let score = 7.5;
  const blockersToNextGrade = [];

  if (!hasStrictGate || p0Open.length > 0 || expiredBlockingWaivers.length > 0) {
    score = Math.min(score, 6.5);
  }
  if (p1Open.length > 0) {
    score = Math.min(score, 7.4);
    blockersToNextGrade.push(`${p1Open.length} P1 code-quality tracker item(s) remain open`);
  }
  if (!hasQualityReportScript) {
    blockersToNextGrade.push('quality report script is not wired into package scripts');
  }
  if (!hasMaintainabilityBudgetGate) {
    blockersToNextGrade.push('maintainability budget gate is not wired into package scripts');
  }
  if (!hasSecurityHygiene || !securityGates.ciRunsJsAudit || !securityGates.ciRunsPythonAudit) {
    blockersToNextGrade.push('security hygiene and dependency audit gates are not fully wired');
  }
  if (!frontendTestEnvironments.policyScript || !frontendTestEnvironments.strictIncludesPolicy) {
    blockersToNextGrade.push('frontend jsdom/browser test environment policy is not fully wired');
  }
  if (!contractParity.configured || !contractParity.ok) {
    blockersToNextGrade.push('contract parity gate is not green or not wired');
  }
  if (
    !uiQualityBudgets.configured ||
    !uiQualityBudgets.script ||
    !uiQualityBudgets.strictIncludesBudget ||
    !uiQualityBudgets.ciRunsPolicy
  ) {
    blockersToNextGrade.push('UI quality budgets are not fully wired');
  }
  if (!realPathCoverage.makeTarget || !realPathCoverage.ciRunsRealPath) {
    blockersToNextGrade.push('real-path integration smoke lane is not fully wired');
  }
  if (blockingBudgetsWithoutDisposition.length > 0) {
    score = Math.min(score, 7.0);
    blockersToNextGrade.push(
      `${blockingBudgetsWithoutDisposition.length} blocking file-size budget row(s) lack a waiver or tracker disposition`,
    );
  }
  if (artifacts.length > 0) {
    blockersToNextGrade.push(
      `${artifacts.length} tracked local/generated artifact row(s) need disposition`,
    );
  }
  if (typeEscapes.length > 0) {
    blockersToNextGrade.push(
      `${typeEscapes.length} frontend source file(s) contain type escape hotspots`,
    );
  }
  if (p0Open.length > 0)
    blockersToNextGrade.push(`${p0Open.length} P0 tracker item(s) remain open`);
  if (expiredBlockingWaivers.length > 0) {
    blockersToNextGrade.push(
      `${expiredBlockingWaivers.length} expired P0/P1 waiver(s) block quality`,
    );
  }
  if (securityWaivers.expired.length > 0) {
    blockersToNextGrade.push(
      `${securityWaivers.expired.length} expired security waiver(s) block quality`,
    );
  }

  return {
    numeric: Number(score.toFixed(1)),
    label: gradeLabel(score),
    blockersToNextGrade,
  };
}

function gradeLabel(score) {
  if (score >= 9.5) return 'A+';
  if (score >= 9.0) return 'A';
  if (score >= 8.5) return 'A-';
  if (score >= 7.5) return 'B';
  if (score >= 7.0) return 'B-';
  if (score >= 6.5) return 'C+';
  return 'C';
}

function thresholdValue(label) {
  if (label === null || label === undefined) return null;
  if (/^\d+(\.\d+)?$/.test(label)) return Number(label);
  if (!(label in GRADE_FLOORS)) {
    throw new Error(`Unknown grade threshold: ${label}`);
  }
  return GRADE_FLOORS[label];
}

function buildReport() {
  const files = trackedFiles();
  const budgetConfig = loadBudgetConfig();
  const sourceRows = loadSourceInventory(files, budgetConfig.fileSizeBudgets);
  const waivers = loadWaivers();
  const securityWaivers = loadSecurityWaivers();
  const budgets = budgetRows(sourceRows, waivers.active, budgetConfig);
  const artifacts = trackedArtifactRows(files, budgetConfig);
  const typeEscapes = typeEscapeHotspots(files);
  const scripts = packageScripts();
  const tracker = trackerRows();
  const backendCoverage = backendCoverageSummary();
  const frontendGates = frontendGateSummary(scripts);
  const contractParity = contractParitySummary(scripts);
  const securityGates = securityGateSummary(scripts);
  const frontendTestEnvironments = frontendTestEnvironmentSummary(scripts);
  const uiQualityBudgets = uiQualityBudgetSummary(scripts);
  const realPathCoverage = realPathCoverageSummary(scripts);
  const grade = computeGrade({
    tracker,
    waivers,
    securityWaivers,
    budgetRows: budgets,
    artifacts,
    typeEscapes,
    scripts,
    securityGates,
    frontendTestEnvironments,
    contractParity,
    uiQualityBudgets,
    realPathCoverage,
  });

  return {
    schemaVersion: 'code-quality-report.v1',
    generatedAt: `${TODAY}T00:00:00.000Z`,
    grade,
    tracker: {
      total: tracker.length,
      done: tracker.filter((row) => row.status === 'Done').length,
      open: tracker.filter((row) => row.status === 'Open').length,
      partial: tracker.filter((row) => row.status === 'Partial').length,
      blocked: tracker.filter((row) => row.status === 'Blocked').length,
      openP0P1: tracker.filter(
        (row) => (row.priority === 'P0' || row.priority === 'P1') && row.status !== 'Done',
      ),
      rows: tracker,
    },
    gates: {
      frontend: frontendGates,
      backendCoverage,
      rootScripts: {
        verify: scripts.root.verify ?? null,
        verifyStrict: scripts.root['verify:strict'] ?? null,
        qualityReport: scripts.root['quality:report'] ?? null,
        qualityWaivers: scripts.root['quality:waivers'] ?? null,
        maintainabilityBudgets: scripts.root['maintainability:budgets'] ?? null,
        contractParity: scripts.root['contract:parity'] ?? null,
        securityHygiene: scripts.root['security:hygiene'] ?? null,
        uiQualityBudgets: scripts.root['ui:quality-budgets'] ?? null,
        architecture: scripts.root.architecture ?? null,
      },
      make: scripts.make,
      contractParity,
      security: securityGates,
      frontendTestEnvironments,
      uiQualityBudgets,
      realPathCoverage,
    },
    maintainability: {
      budgetConfig: {
        path: budgetConfig.path,
        schemaVersion: budgetConfig.schemaVersion,
        targetBlockingDate: budgetConfig.targetBlockingDate,
        ownershipCount: budgetConfig.ownership.length,
        hasComplexityBudgets: Boolean(budgetConfig.complexityBudgets),
      },
      budgets: budgetConfig.fileSizeBudgets,
      largestFiles: sourceRows.slice(0, 25).map(({ path, kind, lines, generated }) => ({
        path,
        kind,
        lines,
        generated,
      })),
      overBudget: budgets,
      overBudgetCount: budgets.length,
      unownedOverBudgetCount: budgets.filter((row) => row.owner === 'unowned').length,
      blockingWithoutDispositionCount: budgets.filter(
        (row) => row.severity === 'blocking' && !row.hasDisposition,
      ).length,
      blockingWithoutWaiverCount: budgets.filter(
        (row) => row.severity === 'blocking' && row.waiverIds.length === 0,
      ).length,
    },
    typeSafety: {
      frontendEscapePattern: FRONTEND_TYPE_ESCAPE_RE.source,
      nonTestHotspotFileCount: typeEscapes.length,
      totalNonTestHotspots: typeEscapes.reduce((sum, row) => sum + row.count, 0),
      topHotspots: typeEscapes.slice(0, 25),
    },
    repositoryHygiene: {
      trackedArtifactCount: artifacts.length,
      trackedArtifacts: artifacts.slice(0, 100),
    },
    waivers: {
      path: waivers.path,
      activeCount: waivers.active.length,
      expiredCount: waivers.expired.length,
      expiringSoonCount: waivers.soon.length,
      active: waivers.active,
      expired: waivers.expired,
      expiringSoon: waivers.soon,
    },
    security: {
      waivers: {
        path: securityWaivers.path,
        activeCount: securityWaivers.active.length,
        expiredCount: securityWaivers.expired.length,
        expiringSoonCount: securityWaivers.soon.length,
        active: securityWaivers.active,
        expired: securityWaivers.expired,
        expiringSoon: securityWaivers.soon,
      },
    },
  };
}

function renderMarkdown(report) {
  const lines = [];
  lines.push('# Code Quality Report');
  lines.push('');
  lines.push(`Generated: ${report.generatedAt}`);
  lines.push('');
  lines.push(`Code Quality Grade: **${report.grade.label} (${report.grade.numeric}/10)**`);
  lines.push('');
  lines.push('## Blocking To Next Grade');
  lines.push('');
  if (report.grade.blockersToNextGrade.length === 0) {
    lines.push('- None.');
  } else {
    for (const blocker of report.grade.blockersToNextGrade) lines.push(`- ${blocker}`);
  }
  lines.push('');
  lines.push('## Tracker');
  lines.push('');
  lines.push('| Total | Done | Open | Partial | Blocked | Open P0/P1 |');
  lines.push('| ----- | ---- | ---- | ------- | ------- | ---------- |');
  lines.push(
    `| ${report.tracker.total} | ${report.tracker.done} | ${report.tracker.open} | ${report.tracker.partial} | ${report.tracker.blocked} | ${report.tracker.openP0P1.length} |`,
  );
  lines.push('');
  lines.push('## Gates');
  lines.push('');
  lines.push('| Gate | Status | Detail |');
  lines.push('| ---- | ------ | ------ |');
  lines.push(
    `| Frontend typecheck | ${report.gates.frontend.strictIncludesTypecheck ? 'configured' : 'missing'} | ${escapeCell(report.gates.frontend.typecheckScript ?? '')} |`,
  );
  lines.push(
    `| Backend coverage | ${report.gates.backendCoverage.configured ? 'configured' : 'missing'} | fail-under ${report.gates.backendCoverage.failUnder ?? 'n/a'} |`,
  );
  lines.push(
    `| Quality report | ${report.gates.rootScripts.qualityReport ? 'configured' : 'missing'} | ${escapeCell(report.gates.rootScripts.qualityReport ?? '')} |`,
  );
  lines.push(
    `| Maintainability budgets | ${report.gates.rootScripts.maintainabilityBudgets ? 'configured' : 'missing'} | make: ${report.gates.make.maintainabilityBudgets ? 'yes' : 'no'} |`,
  );
  lines.push(
    `| Contract parity | ${report.gates.contractParity.ok ? 'pass' : 'fail'} | API descriptors: ${report.gates.contractParity.apiDescriptorCount ?? 'n/a'}, CLI tool IDs: ${report.gates.contractParity.cliToolIdCount ?? 'n/a'}, tracked gaps: ${report.gates.contractParity.baselineMissingDescriptorCount ?? 'n/a'} |`,
  );
  lines.push(
    `| Security hygiene | ${report.gates.security.hygieneScript ? 'configured' : 'missing'} | strict: ${report.gates.security.strictIncludesHygiene ? 'yes' : 'no'}, CI: ${report.gates.security.ciRunsHygiene ? 'yes' : 'no'} |`,
  );
  lines.push(
    `| JS dependency audit | ${report.gates.security.ciRunsJsAudit ? 'configured' : 'missing'} | pnpm audit in CI |`,
  );
  lines.push(
    `| Python dependency audit | ${report.gates.security.ciRunsPythonAudit ? 'configured' : 'missing'} | pip-audit in CI |`,
  );
  lines.push(
    `| Frontend test environments | ${report.gates.frontendTestEnvironments.policyScript ? 'configured' : 'missing'} | strict: ${report.gates.frontendTestEnvironments.strictIncludesPolicy ? 'yes' : 'no'} |`,
  );
  lines.push(
    `| UI quality budgets | ${report.gates.uiQualityBudgets.configured ? 'configured' : 'missing'} | strict: ${report.gates.uiQualityBudgets.strictIncludesBudget ? 'yes' : 'no'}, CI: ${report.gates.uiQualityBudgets.ciRunsPolicy ? 'yes' : 'no'} |`,
  );
  lines.push(
    `| Real-path smoke | ${report.gates.realPathCoverage.ciRunsRealPath ? 'configured' : 'missing'} | app: ${report.gates.realPathCoverage.importsRealApp ? 'yes' : 'no'}, websocket: ${report.gates.realPathCoverage.coversWebsocket ? 'yes' : 'no'} |`,
  );
  lines.push('');
  lines.push('## Maintainability Budgets');
  lines.push('');
  lines.push(
    `Over-budget files: ${report.maintainability.overBudgetCount}; blocking without waiver/tracker: ${report.maintainability.blockingWithoutDispositionCount}; unowned over budget: ${report.maintainability.unownedOverBudgetCount}.`,
  );
  lines.push(
    `Budget config: \`${report.maintainability.budgetConfig.path}\`; target blocking date: ${report.maintainability.budgetConfig.targetBlockingDate ?? 'n/a'}.`,
  );
  lines.push('');
  lines.push('| Lines | Kind | Severity | Owner | Trackers | Waivers | Path |');
  lines.push('| ----- | ---- | -------- | ----- | -------- | ------- | ---- |');
  for (const row of report.maintainability.overBudget.slice(0, 25)) {
    lines.push(
      `| ${row.lines} | ${row.kind} | ${row.severity} | ${row.owner} | ${row.trackerIds.join(', ') || '-'} | ${row.waiverIds.join(', ') || '-'} | ${escapeCell(row.path)} |`,
    );
  }
  if (report.maintainability.overBudget.length === 0) lines.push('| - | - | - | - | - | - | - |');
  lines.push('');
  lines.push('## Type Escape Hotspots');
  lines.push('');
  lines.push(
    `Non-test frontend files with escapes: ${report.typeSafety.nonTestHotspotFileCount}; total matches: ${report.typeSafety.totalNonTestHotspots}.`,
  );
  lines.push('');
  lines.push('| Count | Path |');
  lines.push('| ----- | ---- |');
  for (const row of report.typeSafety.topHotspots.slice(0, 15)) {
    lines.push(`| ${row.count} | ${escapeCell(row.path)} |`);
  }
  if (report.typeSafety.topHotspots.length === 0) lines.push('| 0 | - |');
  lines.push('');
  lines.push('## Repository Hygiene');
  lines.push('');
  lines.push(
    `Tracked local/generated artifact rows: ${report.repositoryHygiene.trackedArtifactCount}.`,
  );
  lines.push('');
  lines.push('| Code | Path |');
  lines.push('| ---- | ---- |');
  for (const row of report.repositoryHygiene.trackedArtifacts.slice(0, 20)) {
    lines.push(`| ${row.code} | ${escapeCell(row.path)} |`);
  }
  if (report.repositoryHygiene.trackedArtifacts.length === 0) lines.push('| - | - |');
  lines.push('');
  lines.push('## Security');
  lines.push('');
  lines.push(
    `Security waivers: active ${report.security.waivers.activeCount}; expiring soon ${report.security.waivers.expiringSoonCount}; expired ${report.security.waivers.expiredCount}.`,
  );
  lines.push('');
  lines.push('| ID | Severity | Code | Expires | Path |');
  lines.push('| -- | -------- | ---- | ------- | ---- |');
  for (const row of report.security.waivers.active) {
    lines.push(
      `| ${row.id} | ${row.severity} | ${escapeCell(row.code)} | ${row.expires} | ${escapeCell(row.path)} |`,
    );
  }
  if (report.security.waivers.active.length === 0) lines.push('| - | - | - | - | - |');
  lines.push('');
  lines.push('## Waivers');
  lines.push('');
  lines.push(
    `Active: ${report.waivers.activeCount}; expiring soon: ${report.waivers.expiringSoonCount}; expired: ${report.waivers.expiredCount}.`,
  );
  lines.push('');
  lines.push('| ID | Severity | Check | Expires | Tracker |');
  lines.push('| -- | -------- | ----- | ------- | ------- |');
  for (const row of report.waivers.active) {
    lines.push(
      `| ${row.id} | ${row.severity} | ${escapeCell(row.check)} | ${row.expires} | ${row.trackerId} |`,
    );
  }
  if (report.waivers.active.length === 0) lines.push('| - | - | - | - | - |');
  lines.push('');
  return `${lines.join('\n')}\n`;
}

function escapeCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function writeOutput(path, data) {
  const abs = join(REPO_ROOT, path);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, data);
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const report = buildReport();
  const json = `${JSON.stringify(report, null, 2)}\n`;
  const markdown = renderMarkdown(report);

  if (args.outJson) writeOutput(args.outJson, json);
  if (args.outMd) writeOutput(args.outMd, markdown);

  process.stdout.write(args.format === 'json' ? json : markdown);

  const threshold = thresholdValue(args.failBelow);
  if (threshold !== null && report.grade.numeric < threshold) {
    console.error(
      `Code quality grade ${report.grade.label} (${report.grade.numeric}) is below threshold ${args.failBelow}`,
    );
    process.exit(1);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}

export { buildReport, renderMarkdown };
