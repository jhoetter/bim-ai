import { flagValue, hasFlag, parseCsv, parseJsonArrayFlag, parseJsonObjectFlag, parseNumber } from './cli-args.mjs';
import { authorOptions, buildGeneratedBundle, runGeneratedBundle } from './generated-bundles.mjs';

export async function cmdDocumentation(modelId, userId, sub, args) {
  if (sub === 'presentation-pack') {
    await cmdDocumentationPresentationPack(modelId, userId, args);
    return;
  }
  if (sub !== 'pack') {
    console.error(
      `Unknown documentation subcommand: ${sub ?? '(none)'}. Use pack | presentation-pack.`,
    );
    process.exit(1);
  }
  const opts = authorOptions(args);
  const sheetId = flagValue(args, '--sheet-id');
  if (!sheetId) {
    console.error('documentation pack requires --sheet-id <id>.');
    process.exit(1);
  }

  const commands = [
    {
      type: 'upsertSheet',
      id: sheetId,
      name: flagValue(args, '--sheet-name') ?? flagValue(args, '--name') ?? 'Drawing sheet',
    },
  ];
  const titleBlock = flagValue(args, ['--title-block', '--titleblock']);
  const paperWidthMm = parseNumber(flagValue(args, '--paper-width'), undefined);
  const paperHeightMm = parseNumber(flagValue(args, '--paper-height'), undefined);
  const titleblockParameters = parseJsonObjectFlag(
    flagValue(args, '--titleblock-parameters'),
    '--titleblock-parameters',
  );
  if (titleBlock) commands[0].titleBlock = titleBlock;
  if (Number.isFinite(paperWidthMm)) commands[0].paperWidthMm = paperWidthMm;
  if (Number.isFinite(paperHeightMm)) commands[0].paperHeightMm = paperHeightMm;
  if (titleblockParameters) commands[0].titleblockParameters = titleblockParameters;

  const viewports = parseJsonArrayFlag(flagValue(args, '--viewports'), '--viewports');
  const scheduleId = flagValue(args, '--schedule-id');
  if (scheduleId) {
    const filters = parseJsonObjectFlag(
      flagValue(args, '--schedule-filters'),
      '--schedule-filters',
    );
    const grouping = parseJsonObjectFlag(
      flagValue(args, '--schedule-grouping'),
      '--schedule-grouping',
    );
    const category = flagValue(args, '--schedule-category');
    commands.push({
      type: 'upsertSchedule',
      id: scheduleId,
      name: flagValue(args, '--schedule-name') ?? 'Schedule',
      sheetId,
      filters: filters ?? (category ? { category } : {}),
      grouping: grouping ?? {},
    });
    if (hasFlag(args, '--place-schedule')) {
      viewports.push({
        viewportId: `vp-${scheduleId}`,
        viewRef: `schedule:${scheduleId}`,
        label: flagValue(args, '--schedule-name') ?? 'Schedule',
        xMm: parseNumber(flagValue(args, '--schedule-x'), 20),
        yMm: parseNumber(flagValue(args, '--schedule-y'), 190),
        widthMm: parseNumber(flagValue(args, '--schedule-width'), 160),
        heightMm: parseNumber(flagValue(args, '--schedule-height'), 70),
      });
    }
  }
  commands.push({ type: 'upsertSheetViewports', sheetId, viewportsMm: viewports });

  for (const tag of parseJsonArrayFlag(flagValue(args, '--tags'), '--tags')) {
    commands.push({ type: 'placeTag', ...tag });
  }
  for (const dimension of parseJsonArrayFlag(flagValue(args, '--dimensions'), '--dimensions')) {
    commands.push({ type: 'createDimension', ...dimension });
  }

  const bundle = buildGeneratedBundle({
    toolId: 'document.create_drawing_set',
    commands,
    parentRevision: opts.parentRevision,
    assumptions: [
      {
        key: 'documentation-export-product-surface',
        value: 'sheet/schedule/viewport/tag/dimension bundle generated by documentation pack',
        confidence: 1,
        source: '@bim-ai/cli documentation pack',
      },
    ],
  });
  await runGeneratedBundle(modelId, userId, bundle, opts.mode, opts.jsonOnly);
}

export async function cmdDocumentationPresentationPack(modelId, userId, args) {
  const opts = authorOptions(args);
  const sheetId = flagValue(args, '--sheet-id');
  const canvasId = flagValue(args, '--canvas-id');
  const viewId = flagValue(args, '--view-id');
  if (!sheetId || !canvasId || !viewId) {
    console.error(
      'documentation presentation-pack requires --sheet-id <id> --canvas-id <id> --view-id <id>.',
    );
    process.exit(1);
  }

  const brandTemplateId = flagValue(args, '--brand-template-id') ?? 'bt-client-pack';
  const scheduleId = flagValue(args, '--schedule-id') ?? 'sch-client-pack';
  const advancedScheduleId = flagValue(args, '--advanced-schedule-id') ?? `${scheduleId}-advanced`;
  const viewTemplateId = flagValue(args, '--view-template-id') ?? 'vt-client-docs';
  const scheduleCategory = flagValue(args, '--schedule-category') ?? 'room';
  const brandName = flagValue(args, '--brand-name') ?? 'Client presentation';
  const accentHex = flagValue(args, '--accent-hex') ?? '#2563eb';
  const accentForegroundHex = flagValue(args, '--accent-foreground-hex') ?? '#ffffff';
  const sheetName = flagValue(args, '--sheet-name') ?? 'Client documentation pack';
  const canvasName = flagValue(args, '--canvas-name') ?? 'Client presentation deck';
  const scheduleName = flagValue(args, '--schedule-name') ?? 'Client schedule';
  const revisionViewId = flagValue(args, '--revision-view-id') ?? viewId;

  const titleblockParameters =
    parseJsonObjectFlag(flagValue(args, '--titleblock-parameters'), '--titleblock-parameters') ??
    {};
  const viewports = parseJsonArrayFlag(flagValue(args, '--viewports'), '--viewports');
  if (!viewports.length) {
    viewports.push(
      {
        viewportId: `vp-${viewId}`,
        viewRef: `plan:${viewId}`,
        label: flagValue(args, '--view-label') ?? 'Primary view',
        xMm: 20,
        yMm: 20,
        widthMm: 160,
        heightMm: 110,
      },
      {
        viewportId: `vp-${scheduleId}`,
        viewRef: `schedule:${scheduleId}`,
        label: scheduleName,
        xMm: 20,
        yMm: 190,
        widthMm: 160,
        heightMm: 70,
      },
    );
  }

  const columns = parseJsonArrayFlag(flagValue(args, '--schedule-columns'), '--schedule-columns');
  const commands = [
    {
      type: 'create_brand_template',
      id: brandTemplateId,
      name: brandName,
      accentHex,
      accentForegroundHex,
      typeface: flagValue(args, '--typeface') ?? 'Inter',
    },
    {
      type: 'upsertViewTemplate',
      id: viewTemplateId,
      name: flagValue(args, '--view-template-name') ?? 'Client documentation view',
      scale: flagValue(args, '--view-scale') ?? 'scale_100',
      disciplinesVisible: parseCsv(flagValue(args, '--disciplines-visible')),
      hiddenCategories: parseCsv(flagValue(args, '--hidden-categories') ?? 'analytical,workplane'),
      planDetailLevel: flagValue(args, '--plan-detail-level') ?? 'fine',
      planShowRoomLabels: true,
      planShowOpeningTags: true,
    },
    { type: 'applyPlanViewTemplate', planViewId: viewId, templateId: viewTemplateId },
    {
      type: 'upsertSheet',
      id: sheetId,
      name: sheetName,
      titleBlock: flagValue(args, '--title-block') ?? 'client-branded-titleblock',
      titleblockParameters: {
        issueStatus: flagValue(args, '--issue-status') ?? 'Client review',
        brandTemplateId,
        ...titleblockParameters,
      },
    },
    {
      type: 'upsertSchedule',
      id: scheduleId,
      name: scheduleName,
      sheetId,
      filters: parseJsonObjectFlag(flagValue(args, '--schedule-filters'), '--schedule-filters') ?? {
        category: scheduleCategory,
      },
      grouping: parseJsonObjectFlag(
        flagValue(args, '--schedule-grouping'),
        '--schedule-grouping',
      ) ?? { sortBy: flagValue(args, '--schedule-sort') ?? 'name' },
    },
    {
      type: 'create_schedule_view',
      id: advancedScheduleId,
      name: flagValue(args, '--advanced-schedule-name') ?? `${scheduleName} advanced`,
      category: scheduleCategory,
      columns: columns.length
        ? columns
        : [
            { key: 'name', label: 'Name' },
            { key: 'levelId', label: 'Level' },
            { key: 'programmeCode', label: 'Programme' },
          ],
      filterExpr: flagValue(args, '--schedule-filter-expr') ?? `category == "${scheduleCategory}"`,
      sortKey: flagValue(args, '--schedule-sort-key') ?? 'name',
      sortDir: flagValue(args, '--schedule-sort-dir') ?? 'asc',
    },
    { type: 'upsertSheetViewports', sheetId, viewportsMm: viewports },
    {
      type: 'createRevisionCloud',
      id: flagValue(args, '--revision-cloud-id') ?? 'rev-client-pack-01',
      hostViewId: revisionViewId,
      boundaryMm: parseJsonArrayFlag(flagValue(args, '--revision-boundary'), '--revision-boundary')
        .length
        ? parseJsonArrayFlag(flagValue(args, '--revision-boundary'), '--revision-boundary')
        : [
            { xMm: 500, yMm: 500 },
            { xMm: 2500, yMm: 500 },
            { xMm: 2500, yMm: 1500 },
            { xMm: 500, yMm: 1500 },
          ],
      colour: flagValue(args, '--revision-colour') ?? '#e05000',
      strokeMm: parseNumber(flagValue(args, '--revision-stroke'), 1.0),
    },
    { type: 'create_presentation_canvas', id: canvasId, name: canvasName },
  ];

  const frames = parseJsonArrayFlag(flagValue(args, '--frames'), '--frames');
  const frameSpecs = frames.length
    ? frames
    : [
        {
          id: 'frame-primary-view',
          viewId,
          caption: flagValue(args, '--view-caption') ?? 'Primary drawing view',
          positionMm: { xMm: 0, yMm: 0 },
          sizeMm: { widthMm: 210, heightMm: 118 },
          sortOrder: 0,
        },
        {
          id: 'frame-schedule',
          viewId: scheduleId,
          caption: scheduleName,
          positionMm: { xMm: 0, yMm: 118 },
          sizeMm: { widthMm: 210, heightMm: 80 },
          sortOrder: 1,
        },
      ];
  for (const frame of frameSpecs) {
    commands.push({
      type: 'create_frame',
      presentationCanvasId: canvasId,
      brandTemplateId,
      ...frame,
    });
  }

  const bundle = buildGeneratedBundle({
    toolId: 'presentation.documentation_pack',
    commands,
    parentRevision: opts.parentRevision,
    assumptions: [
      {
        key: 'presentation-documentation-export-routes',
        value: {
          presentation: `/api/v3/models/${modelId}/presentation-canvases/${canvasId}/export`,
          brandedPdf: `/api/v3/models/${modelId}/export/pdf?brandTemplateId=${brandTemplateId}`,
          renderBundle: `/api/v3/models/${modelId}/export?format=gltf-pbr`,
          documentationEvidence: 'documentationExportProductionEvidence_v1',
        },
        confidence: 1,
        source: '@bim-ai/cli documentation presentation-pack',
      },
    ],
  });
  await runGeneratedBundle(modelId, userId, bundle, opts.mode, opts.jsonOnly);
}
